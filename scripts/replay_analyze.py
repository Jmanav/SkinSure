"""Analyze A2 replay results and write a markdown report.

    ./venv/Scripts/python.exe scripts/replay_analyze.py
    ./venv/Scripts/python.exe scripts/replay_analyze.py --results path/to/results.jsonl
"""
from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = ROOT / "data" / "eval" / "replay_v1" / "results.jsonl"
REPORT_PATH = ROOT / ".nb1out" / "replay_v1_dryrun_analysis.md"

CLASSES = ["Basal_Cell_Carcinoma", "Eczema", "Keratosis", "Melanoma", "Tinea"]
MALIGNANT = {"Basal_Cell_Carcinoma", "Melanoma"}
BENIGN = {"Eczema", "Keratosis", "Tinea"}


def load(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def fmt_pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "N/A"


def table(headers: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    if align is None:
        align = ["l"] * len(headers)
    sep = []
    for a in align:
        if a == "r":
            sep.append("---:")
        elif a == "c":
            sep.append(":---:")
        else:
            sep.append(":---")
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(sep) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(lines)


def analyze(rows: list[dict]) -> str:
    out: list[str] = []
    out.append("# A2 Replay — Dry-Run Analysis")
    out.append("")
    out.append(f"**Date:** generated by `scripts/replay_analyze.py`  ")
    out.append(f"**Source:** `data/eval/replay_v1/results.jsonl` ({len(rows)} images, dry_run=true)  ")
    out.append("**Note:** LLM summaries are canned FakeClient text. Ensemble predictions, triage rules, "
               "XAI, and preprocessing are real.")
    out.append("")

    # Split by status
    completed = [r for r in rows if r["status"] == "completed"]
    rejected = [r for r in rows if r["status"] == "rejected"]
    blocked = [r for r in rows if r["status"] == "blocked"]
    errored = [r for r in rows if r["error"] is not None]

    out.append("---")
    out.append("")
    out.append("## 1. Pipeline Status")
    out.append("")
    out.append(f"- **Completed:** {len(completed)}")
    out.append(f"- **Rejected** (quality gate): {len(rejected)}")
    out.append(f"- **Blocked** (low confidence → retake): {len(blocked)}")
    out.append(f"- **Errors:** {len(errored)}")
    if rejected:
        out.append("")
        out.append("**Rejected images:**")
        for r in rejected:
            out.append(f"- `{r['image_path']}` ({r['true_class']}): {'; '.join(r.get('messages', []))}")
    if blocked:
        out.append("")
        out.append("**Blocked images:**")
        for r in blocked:
            reasons = "; ".join(r.get("triage_reasons", []))
            out.append(f"- `{r['image_path']}` ({r['true_class']}): predicted={r['primary_label']} "
                       f"@ {r['primary_confidence']:.3f} — {reasons}")

    # Accuracy only on completed rows
    scoreable = completed
    correct = [r for r in scoreable if r["primary_label"] == r["true_class"]]

    out.append("")
    out.append("---")
    out.append("")
    out.append("## 2. Overall Accuracy")
    out.append("")
    out.append(f"**{len(correct)} / {len(scoreable)} = {fmt_pct(len(correct), len(scoreable))}** "
               f"(on {len(scoreable)} completed images; {len(rows) - len(scoreable)} excluded: "
               f"{len(rejected)} rejected, {len(blocked)} blocked)")
    out.append("")

    # Per-class accuracy
    out.append("---")
    out.append("")
    out.append("## 3. Per-Class Accuracy")
    out.append("")
    cls_rows = []
    for cls in CLASSES:
        total = [r for r in scoreable if r["true_class"] == cls]
        right = [r for r in total if r["primary_label"] == cls]
        cls_rows.append([cls, str(len(right)), str(len(total)), fmt_pct(len(right), len(total))])
    out.append(table(["Class", "Correct", "Total", "Accuracy"], cls_rows, ["l", "r", "r", "r"]))
    out.append("")

    # Confusion matrix
    out.append("---")
    out.append("")
    out.append("## 4. Confusion Matrix (predicted × true)")
    out.append("")
    out.append("Rows = true class, columns = predicted class. Only completed images.")
    out.append("")
    cm: dict[str, Counter] = {cls: Counter() for cls in CLASSES}
    for r in scoreable:
        cm[r["true_class"]][r["primary_label"]] += 1
    headers = ["True \\ Predicted"] + [c.split("_")[0] for c in CLASSES]
    cm_rows = []
    for cls in CLASSES:
        row = [cls]
        for pred in CLASSES:
            v = cm[cls].get(pred, 0)
            row.append(f"**{v}**" if pred == cls else str(v))
        cm_rows.append(row)
    out.append(table(headers, cm_rows, ["l"] + ["r"] * len(CLASSES)))
    out.append("")

    # Misclassifications detail
    misclassified = [r for r in scoreable if r["primary_label"] != r["true_class"]]
    out.append("---")
    out.append("")
    out.append("## 5. Misclassification Detail")
    out.append("")
    if misclassified:
        mis_rows = []
        for r in misclassified:
            mis_rows.append([
                f"`{r['image_path']}`",
                r["true_class"],
                r["primary_label"],
                f"{r['primary_confidence']:.3f}",
                r["confidence_tier"],
            ])
        out.append(table(
            ["Image", "True", "Predicted", "Confidence", "Tier"],
            mis_rows,
            ["l", "l", "l", "r", "c"],
        ))
    else:
        out.append("No misclassifications.")
    out.append("")

    # Triage analysis
    out.append("---")
    out.append("")
    out.append("## 6. Triage Analysis")
    out.append("")
    escalated = [r for r in rows if r["escalated"]]
    reason_counts: Counter = Counter()
    for r in rows:
        for reason in r.get("triage_reasons", []):
            prefix = reason.split(" ")[0]
            if "melanoma" in reason.lower():
                reason_counts["melanoma escalation"] += 1
            elif "spreading" in reason.lower():
                reason_counts["rapidly spreading infection"] += 1
            elif "confidence" in reason.lower():
                reason_counts["low confidence block"] += 1
            else:
                reason_counts[reason] += 1
    out.append(f"- **Escalated to urgent:** {len(escalated)}")
    out.append(f"- **Blocked (retake):** {len(blocked)}")
    out.append(f"- **Treatment advice suppressed:** {sum(1 for r in rows if not r['treatment_advice_allowed'])}")
    out.append("")
    if reason_counts:
        out.append("**Triage reasons breakdown:**")
        out.append("")
        for reason, count in reason_counts.most_common():
            out.append(f"- {reason}: {count}")
    out.append("")

    # Safety check
    out.append("---")
    out.append("")
    out.append("## 7. Safety Check")
    out.append("")

    mel_as_benign = [r for r in scoreable if r["true_class"] == "Melanoma" and r["primary_label"] in BENIGN]
    bcc_as_benign = [r for r in scoreable if r["true_class"] == "Basal_Cell_Carcinoma" and r["primary_label"] in BENIGN]
    mel_not_escalated = [r for r in scoreable if r["true_class"] == "Melanoma" and not r["escalated"]]

    if mel_as_benign:
        out.append(f"**ALERT: {len(mel_as_benign)} melanoma(s) predicted as benign:**")
        for r in mel_as_benign:
            out.append(f"- `{r['image_path']}` → {r['primary_label']} @ {r['primary_confidence']:.3f}")
    else:
        out.append("- No melanomas predicted as a benign class.")

    if bcc_as_benign:
        out.append(f"**WARNING: {len(bcc_as_benign)} BCC(s) predicted as benign:**")
        for r in bcc_as_benign:
            out.append(f"- `{r['image_path']}` → {r['primary_label']} @ {r['primary_confidence']:.3f}")
    else:
        out.append("- No BCCs predicted as a benign class.")

    if mel_not_escalated:
        out.append(f"**ALERT: {len(mel_not_escalated)} melanoma(s) NOT escalated to urgent:**")
        for r in mel_not_escalated:
            out.append(f"- `{r['image_path']}` → predicted {r['primary_label']} @ {r['primary_confidence']:.3f}, "
                       f"triage: {r.get('severity', 'N/A')}")
    else:
        out.append("- All melanomas were escalated to urgent.")

    out.append("")

    # XAI distribution
    out.append("---")
    out.append("")
    out.append("## 8. XAI Distribution")
    out.append("")
    out.append("Only completed images (XAI runs after ensemble).")
    out.append("")
    focus_counts = Counter(r["xai_focus"] for r in completed)
    boundary_counts = Counter(r["xai_boundary"] for r in completed)
    artifact_flags = sum(1 for r in completed if r["xai_artifact_flag"])

    out.append("**Focus description:**")
    out.append("")
    for val in ["lesion_centre", "lesion_border", "diffuse", "background_skin", "artifact", "unknown"]:
        n = focus_counts.get(val, 0)
        out.append(f"- `{val}`: {n} ({fmt_pct(n, len(completed))})")
    out.append("")

    out.append("**Boundary alignment:**")
    out.append("")
    for val in ["good", "partial", "poor", "unknown"]:
        n = boundary_counts.get(val, 0)
        out.append(f"- `{val}`: {n} ({fmt_pct(n, len(completed))})")
    out.append("")
    out.append(f"**Artifact flags:** {artifact_flags} / {len(completed)}")
    out.append("")

    good_count = boundary_counts.get("good", 0)
    out.append(f"> **Gap 7 confirmation:** `boundary_alignment=good` appeared on **{good_count}** of "
               f"{len(completed)} completed images "
               f"({fmt_pct(good_count, len(completed))}). "
               f"The earlier 15-image run found 0/15 good; this 50-image run "
               f"{'confirms' if good_count <= 2 else 'partially contradicts'} the pattern. "
               f"`poor` dominates at {boundary_counts.get('poor', 0)}/{len(completed)} "
               f"({fmt_pct(boundary_counts.get('poor', 0), len(completed))}), "
               f"with `unknown` at {boundary_counts.get('unknown', 0)} — "
               f"threshold re-tuning (gap 7) is clearly needed.")
    out.append("")

    # Confidence analysis
    out.append("---")
    out.append("")
    out.append("## 9. Confidence Analysis")
    out.append("")
    tier_counts = Counter(r["confidence_tier"] for r in completed)
    for tier in ["high", "moderate", "low"]:
        n = tier_counts.get(tier, 0)
        out.append(f"- `{tier}`: {n} ({fmt_pct(n, len(completed))})")
    out.append("")

    agreement_vals = [r["agreement_score"] for r in completed]
    agreement_counts = Counter(f"{v:.2f}" for v in agreement_vals)
    out.append("**Agreement score distribution:**")
    out.append("")
    for val in sorted(agreement_counts):
        out.append(f"- {val}: {agreement_counts[val]}")
    out.append("")

    # Timing
    out.append("---")
    out.append("")
    out.append("## 10. Timing")
    out.append("")
    times = [r["elapsed_s"] for r in rows]
    out.append(f"- **Mean:** {statistics.mean(times):.1f}s")
    out.append(f"- **Median:** {statistics.median(times):.1f}s")
    out.append(f"- **Max:** {max(times):.1f}s (`{max(rows, key=lambda r: r['elapsed_s'])['image_path']}`)")
    out.append(f"- **Min:** {min(times):.1f}s")
    out.append("")

    out.append("**Per-class timing (completed only):**")
    out.append("")
    timing_rows = []
    for cls in CLASSES:
        cls_times = [r["elapsed_s"] for r in completed if r["true_class"] == cls]
        if cls_times:
            timing_rows.append([
                cls,
                f"{statistics.mean(cls_times):.1f}s",
                f"{statistics.median(cls_times):.1f}s",
                f"{max(cls_times):.1f}s",
            ])
    out.append(table(["Class", "Mean", "Median", "Max"], timing_rows, ["l", "r", "r", "r"]))
    out.append("")

    # Errors
    out.append("---")
    out.append("")
    out.append("## 11. Errors")
    out.append("")
    if errored:
        for r in errored:
            out.append(f"- `{r['image_path']}`: {r['error']}")
    else:
        out.append("No errors.")
    out.append("")

    # Summary / failure taxonomy
    out.append("---")
    out.append("")
    out.append("## 12. Failure Taxonomy (feeds A3 prompt hardening)")
    out.append("")

    # Categorize failures
    keratosis_misses = [r for r in misclassified if r["true_class"] == "Keratosis"]
    tinea_misses = [r for r in misclassified if r["true_class"] == "Tinea"]
    mel_misses = [r for r in misclassified if r["true_class"] == "Melanoma"]

    out.append("### Failure modes by severity")
    out.append("")

    if mel_misses or mel_not_escalated:
        out.append("**CRITICAL — Melanoma safety failures:**")
        for r in mel_misses:
            out.append(f"- `{r['image_path']}`: true Melanoma → {r['primary_label']} "
                       f"@ {r['primary_confidence']:.3f} (tier: {r['confidence_tier']}, "
                       f"escalated: {r['escalated']})")
        out.append("")

    out.append("**HIGH — Keratosis confusion (weakest class):**")
    if keratosis_misses:
        for r in keratosis_misses:
            out.append(f"- `{r['image_path']}`: true Keratosis → {r['primary_label']} "
                       f"@ {r['primary_confidence']:.3f}")
        ker_total = len([r for r in scoreable if r["true_class"] == "Keratosis"])
        out.append(f"- **{len(keratosis_misses)} / {ker_total} Keratosis images misclassified** — "
                   f"consistent with NB1 ablation showing Keratosis as the weakest class.")
    out.append("")

    if tinea_misses:
        out.append("**MODERATE — Tinea↔Eczema confusion:**")
        for r in tinea_misses:
            out.append(f"- `{r['image_path']}`: true Tinea → {r['primary_label']} "
                       f"@ {r['primary_confidence']:.3f}")
        out.append("")

    out.append("### Patterns")
    out.append("")

    # What classes get confused with what
    confusion_pairs: Counter = Counter()
    for r in misclassified:
        confusion_pairs[(r["true_class"], r["primary_label"])] += 1
    if confusion_pairs:
        out.append("**Most common confusion pairs:**")
        out.append("")
        for (true, pred), count in confusion_pairs.most_common():
            out.append(f"- {true} → {pred}: {count}")
    out.append("")

    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description="Analyze A2 replay results")
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--report", type=Path, default=REPORT_PATH)
    args = parser.parse_args()

    rows = load(args.results)
    report = analyze(rows)

    import sys, io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    print(report)

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report, encoding="utf-8")
    print(f"\n\n--- Report saved to {args.report} ---")


if __name__ == "__main__":
    main()
